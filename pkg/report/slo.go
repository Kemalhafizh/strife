// SLOGate defines quantitative resilience thresholds for a run.
type SLOGate struct {
	MaxMTTR         time.Duration `json:"max_mttr,omitempty"`
	MinAvailability float64       `json:"min_availability,omitempty"`
}

// Enabled reports whether at least one SLO threshold is configured.
func (g SLOGate) Enabled() bool {
	return g.MaxMTTR > 0 || g.MinAvailability > 0
}

// NormalizedMinAvailability returns MinAvailability in [0, 1], accepting
// either a ratio (0.995) or a percentage (99.5).
func (g SLOGate) NormalizedMinAvailability() float64 {
	if g.MinAvailability > 1.0 {
		return g.MinAvailability / 100.0
	}
	return g.MinAvailability
}

// SLOResult records the outcome of evaluating an SLOGate against ResilienceMetrics.
type SLOResult struct {
	Passed               bool          `json:"passed"`
	MaxMTTR              time.Duration `json:"max_mttr,omitempty"`
	ObservedMaxMTTR      time.Duration `json:"observed_max_mttr,omitempty"`
	ObservedP95MTTR      time.Duration `json:"observed_p95_mttr,omitempty"`
	UnrecoveredFaults    int           `json:"unrecovered_faults,omitempty"`
	MinAvailability      float64       `json:"min_availability,omitempty"`
	ObservedAvailability float64       `json:"observed_availability"`
	Violations           []string      `json:"violations,omitempty"`
}

// EvaluateSLO checks whether the measured resilience metrics satisfy gate.
func EvaluateSLO(res *ResilienceMetrics, gate SLOGate) *SLOResult {
	minAvail := gate.NormalizedMinAvailability()
	out := &SLOResult{
		Passed:          true,
		MaxMTTR:         gate.MaxMTTR,
		MinAvailability: minAvail,
	}
	if !gate.Enabled() {
		if res != nil {
			out.ObservedAvailability = res.OverallAvailability
			out.ObservedMaxMTTR = res.MTTR.Max
			out.ObservedP95MTTR = res.MTTR.P95
		}
		return out
	}
	if res == nil {
		out.Passed = false
		out.Violations = append(out.Violations, "no resilience metrics recorded (empty history)")
		return out
	}

	out.ObservedAvailability = res.OverallAvailability
	out.ObservedMaxMTTR = res.MTTR.Max
	out.ObservedP95MTTR = res.MTTR.P95
	for _, fr := range res.Recoveries {
		if !fr.RecoveredOK {
			out.UnrecoveredFaults++
		}
	}

	if minAvail > 0 && res.OverallAvailability+1e-9 < minAvail {
		out.Passed = false
		out.Violations = append(out.Violations,
			fmt.Sprintf("overall availability %.2f%% is below minimum SLO %.2f%%",
				100*res.OverallAvailability, 100*minAvail))
	}
	if gate.MaxMTTR > 0 {
		if out.UnrecoveredFaults > 0 {
			out.Passed = false
			out.Violations = append(out.Violations,
				fmt.Sprintf("%d healed fault(s) did not recover before the end of the run (max MTTR SLO %v)",
					out.UnrecoveredFaults, gate.MaxMTTR))
		} else if res.MTTR.Count > 0 && res.MTTR.Max > gate.MaxMTTR {
			out.Passed = false
			out.Violations = append(out.Violations,
				fmt.Sprintf("max recovery latency (MTTR) %v exceeds SLO threshold %v (p95 %v)",
					stats.Round(res.MTTR.Max), gate.MaxMTTR, stats.Round(res.MTTR.P95)))
		}
	}
	return out
}

// SLOCase converts an SLOResult into a CI test case for JUnit XML and step summaries.
func SLOCase(res *SLOResult, class string) Case {
	c := Case{
		Name:   "resilience SLO gate",
		Class:  class,
		Status: Passed,
		Output: fmt.Sprintf("availability %.2f%%, max MTTR %v", 100*res.ObservedAvailability, stats.Round(res.ObservedMaxMTTR)),
	}
	if !res.Passed {
		c.Status = Failed
		c.Message = strings.Join(res.Violations, "; ")
		c.Detail = c.Message
	}
	return c
}

// PRCampaignSummary holds campaign regression fields for a PR digest.
type PRCampaignSummary struct {
	CampaignID     string
	System         string
	TotalSeeds     int
	Passed         int
	Violations     int
	RegressedSeeds []uint64
	FixedSeeds     []uint64
	NewFailures    []uint64
	TraceDrifts    int
	Reproduce      string
}

// PRDigestOptions configures the Markdown Pull Request comment generated by WritePRDigest.
type PRDigestOptions struct {
	Report         *Report
	BaselineReport *Report
	Campaign       *PRCampaignSummary
	SLO            *SLOResult
	CompliancePass *bool
	ComplianceNote string
}

// WritePRDigest renders a comparative Markdown report suitable for posting as
// a GitHub/GitLab Pull Request comment or CI step summary. It returns true if
// all checks (consistency, regressions, SLO gates, compliance) passed.
func WritePRDigest(w io.Writer, opts PRDigestOptions) (bool, error) {
	passed := true
	if opts.Report != nil && opts.Report.Verdict != checker.Linearizable {
		passed = false
	}
	if opts.Campaign != nil {
		if opts.Campaign.Violations > 0 && len(opts.Campaign.RegressedSeeds) > 0 {
			passed = false
		}
		if len(opts.Campaign.RegressedSeeds) > 0 || len(opts.Campaign.NewFailures) > 0 {
			passed = false
		}
	}
	if opts.SLO != nil && !opts.SLO.Passed {
		passed = false
	}
	if opts.CompliancePass != nil && !*opts.CompliancePass {
		passed = false
	}

	var b strings.Builder
	badge := "✅ **PASS**"
	if !passed {
		badge = "❌ **FAIL**"
	}
	target := "verification"
	if opts.Report != nil && opts.Report.Target != "" {
		target = opts.Report.Target
	} else if opts.Campaign != nil && opts.Campaign.System != "" {
		target = opts.Campaign.System
	}
	fmt.Fprintf(&b, "## Strife CI Gate · `%s` — %s\n\n", target, badge)

	if r := opts.Report; r != nil {
		st := r.Check.Stats
		fmt.Fprintf(&b, "| Check | Status | Details |\n|---|---|---|\n")
		vIcon := "✅"
		if r.Verdict != checker.Linearizable {
			vIcon = "❌"
		}
		fmt.Fprintf(&b, "| Consistency (`%s`) | %s `%s` | %d ops (%d ok, %d fail, %d info) · seed `%d` |\n",
			r.Check.Model, vIcon, strings.ToUpper(string(r.Verdict)), st.Invocations, st.OK, st.Fail, st.Info, r.Seed)

		if res := r.Resilience; res != nil {
			availDelta := ""
			mttrDelta := ""
			if base := opts.BaselineReport; base != nil && base.Resilience != nil {
				diffA := 100 * (res.OverallAvailability - base.Resilience.OverallAvailability)
				availDelta = fmt.Sprintf(" (%+.1f%% vs baseline)", diffA)
				if res.MTTR.Count > 0 && base.Resilience.MTTR.Count > 0 {
					diffM := res.MTTR.P95 - base.Resilience.MTTR.P95
					mttrDelta = fmt.Sprintf(" (%+v vs baseline)", stats.Round(diffM))
				}
			}
			fmt.Fprintf(&b, "| Availability | `%.1f%%`%s | healthy `%.1f%%` · fault windows `%.1f%%` |\n",
				100*res.OverallAvailability, availDelta, 100*res.HealthyWindowAvailability, 100*res.FaultWindowAvailability)
			if res.MTTR.Count > 0 {
				fmt.Fprintf(&b, "| Recovery Latency (MTTR) | p95 `%v`%s | p50 `%v` · max `%v` (%d healed faults) |\n",
					stats.Round(res.MTTR.P95), mttrDelta, stats.Round(res.MTTR.P50), stats.Round(res.MTTR.Max), res.MTTR.Count)
			}
		}

		if slo := opts.SLO; slo != nil && (slo.MaxMTTR > 0 || slo.MinAvailability > 0) {
			sIcon := "✅ PASS"
			detail := "all resilience SLO thresholds satisfied"
			if !slo.Passed {
				sIcon = "❌ FAIL"
				detail = strings.Join(slo.Violations, "; ")
			}
			fmt.Fprintf(&b, "| Resilience SLO Gate | %s | %s |\n", sIcon, mdCell(detail))
		}
		if opts.CompliancePass != nil {
			cIcon := "✅ PASS"
			if !*opts.CompliancePass {
				cIcon = "❌ FAIL"
			}
			fmt.Fprintf(&b, "| Regulatory Compliance | %s | %s |\n", cIcon, mdCell(opts.ComplianceNote))
		}
		b.WriteString("\n")
		if r.Reproduce != "" && r.Verdict != checker.Linearizable {
			fmt.Fprintf(&b, "**Reproduce:**\n```sh\n%s\n```\n\n", r.Reproduce)
		}
	}

	if c := opts.Campaign; c != nil {
		fmt.Fprintf(&b, "### Campaign Summary (`%s`)\n\n", c.System)
		fmt.Fprintf(&b, "| Seeds | Passed | Violations | Regressed | Fixed | Trace Drifts |\n|---|---|---|---|---|---|\n")
		fmt.Fprintf(&b, "| %d | %d | %d | %d | %d | %d |\n\n",
			c.TotalSeeds, c.Passed, c.Violations, len(c.RegressedSeeds), len(c.FixedSeeds), c.TraceDrifts)
		if len(c.RegressedSeeds) > 0 {
			fmt.Fprintf(&b, "- ❌ **Regressed seeds:** `%v`\n", c.RegressedSeeds)
		}
		if len(c.FixedSeeds) > 0 {
			fmt.Fprintf(&b, "- ✅ **Fixed seeds:** `%v`\n", c.FixedSeeds)
		}
		if c.Reproduce != "" {
			fmt.Fprintf(&b, "\n**Reproduce failing seed:**\n```sh\n%s\n```\n\n", c.Reproduce)
		}
	}

	_, err := io.WriteString(w, b.String())
	return passed, err
}
